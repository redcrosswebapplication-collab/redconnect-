create or replace function public.mark_all_notifications_read()
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_profile_id bigint := public.current_profile_id();
begin
  if v_profile_id is null then
    raise exception using errcode = 'P0001', message = 'Please log in again';
  end if;
  insert into public.notification_reads (user_id, notification_id)
  select v_profile_id, n.id
    from public.notifications n
    where n.user_id is null or n.user_id = v_profile_id
  on conflict do nothing;
end;
$$;

create or replace function public.get_unread_notification_count()
returns integer
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
declare
  v_profile_id bigint := public.current_profile_id();
  v_unread integer;
begin
  if v_profile_id is null then
    raise exception using errcode = 'P0001', message = 'Please log in again';
  end if;
  select count(*)::integer into v_unread
    from public.notifications n
    where (n.user_id is null or n.user_id = v_profile_id)
      and not exists (
        select 1 from public.notification_reads r
        where r.user_id = v_profile_id and r.notification_id = n.id
      );
  return v_unread;
end;
$$;

create or replace function public.handle_donor_verification_change()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if tg_op = 'INSERT' then
    if extract(year from age(
      (now() at time zone 'Asia/Manila')::date, new.birth_date
    )) not between 18 and 65 then
      raise exception using errcode = 'P0001',
        message = 'Donors must be between 18 and 65 years old';
    end if;
    if auth.uid() is not null and (
      new.id_front_path not like (auth.uid()::text || '/%')
      or new.id_back_path not like (auth.uid()::text || '/%')
    ) then
      raise exception using errcode = 'P0001', message = 'Invalid ID image paths';
    end if;
    insert into public.notifications (user_id, type, title, body)
    values (new.user_id, 'donor', 'Verification submitted',
            'We are reviewing your documents. You will be notified once done.');
  elsif new.status is distinct from old.status then
    new.reviewed_at := now();
    update public.profiles
      set is_donor = (new.status = 'approved')
      where id = new.user_id;
    insert into public.notifications (user_id, type, title, body)
    values (
      new.user_id,
      'donor',
      'Donor verification ' || replace(new.status, '_', ' '),
      coalesce(new.note, 'Your donor verification is now ' || replace(new.status, '_', ' ') || '.')
    );
  end if;
  return new;
end;
$$;

