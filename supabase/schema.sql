create or replace function public.get_appointment_availability(p_date date)
returns table (slot_time text, remaining integer)
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
declare
  v_slot time;
  v_now timestamp := now() at time zone 'Asia/Manila';
  v_slots time[] := array[
    time '08:00', time '09:00', time '10:00', time '11:00',
    time '13:00', time '14:00', time '15:00', time '16:00'
  ];
begin
  if p_date is null or p_date < v_now::date or extract(dow from p_date) = 0 then
    return;
  end if;
  foreach v_slot in array v_slots loop
    if p_date > v_now::date or v_slot > v_now::time then
      slot_time := to_char(v_slot, 'HH24:MI');
      select greatest(0, 5 - count(*)::integer)
        into remaining
        from public.appointments a
        where a.preferred_date = p_date
          and a.preferred_time = v_slot
          and a.status in ('pending', 'confirmed');
      return next;
    end if;
  end loop;
end;
$$;

create or replace function public.book_appointment(
  p_full_name text,
  p_phone text,
  p_date date,
  p_time time
)
returns public.appointments
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_profile_id bigint := public.current_profile_id();
  v_now timestamp := now() at time zone 'Asia/Manila';
  v_appointment public.appointments;
  v_remaining integer;
begin
  if auth.uid() is null or v_profile_id is null then
    raise exception using errcode = 'P0001', message = 'Please log in again';
  end if;
  if p_full_name is null or length(trim(p_full_name)) not between 2 and 100
     or p_phone is null or length(trim(p_phone)) < 7 then
    raise exception using errcode = 'P0001', message = 'Enter a valid name and phone number';
  end if;
  if p_time not in (
    time '08:00', time '09:00', time '10:00', time '11:00',
    time '13:00', time '14:00', time '15:00', time '16:00'
  ) or p_date < v_now::date or extract(dow from p_date) = 0
    or (p_date = v_now::date and p_time <= v_now::time) then
    raise exception using errcode = 'P0001', message = 'That time is not available';
  end if;

  perform pg_advisory_xact_lock(hashtext(v_profile_id::text || ':' || p_date::text));
  perform pg_advisory_xact_lock(hashtext(p_date::text || ':' || p_time::text));
  if exists (
    select 1 from public.appointments
    where user_id = v_profile_id and preferred_date = p_date
      and status in ('pending', 'confirmed')
  ) then
    raise exception using errcode = 'P0001', message = 'You already have an appointment on that date';
  end if;
  select 5 - count(*)::integer into v_remaining
    from public.appointments
    where preferred_date = p_date and preferred_time = p_time
      and status in ('pending', 'confirmed');
  if v_remaining <= 0 then
    raise exception using errcode = 'P0001', message = 'That slot is already full';
  end if;

  insert into public.appointments (user_id, full_name, phone, preferred_date, preferred_time)
  values (v_profile_id, trim(p_full_name), trim(p_phone), p_date, p_time)
  returning * into v_appointment;
  insert into public.notifications (user_id, type, title, body)
  values (v_profile_id, 'update', 'Appointment booked',
          p_date::text || ' at ' || to_char(p_time, 'HH24:MI') || '. We''ll confirm it shortly.');
  return v_appointment;
end;
$$;

create or replace function public.cancel_appointment(p_id bigint)
returns public.appointments
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_appointment public.appointments;
begin
  update public.appointments
    set status = 'cancelled'
    where id = p_id and user_id = public.current_profile_id()
      and status in ('pending', 'confirmed')
    returning * into v_appointment;
  if not found then
    raise exception using errcode = 'P0001', message = 'This appointment can no longer be cancelled';
  end if;
  return v_appointment;
end;
$$;

create or replace function public.create_blood_request(
  p_patient_name text,
  p_contact_person text,
  p_contact_number text,
  p_blood_group text,
  p_units integer,
  p_hospital text,
  p_address text,
  p_city text,
  p_urgency text,
  p_notes text
)
returns public.blood_requests
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_profile_id bigint := public.current_profile_id();
  v_request public.blood_requests;
begin
  if auth.uid() is null or v_profile_id is null then
    raise exception using errcode = 'P0001', message = 'Please log in again';
  end if;
  if length(trim(coalesce(p_patient_name, ''))) not between 2 and 100
     or length(trim(coalesce(p_contact_person, ''))) not between 2 and 100
     or length(trim(coalesce(p_contact_number, ''))) < 7
     or p_blood_group not in ('A+', 'A-', 'B+', 'B-', 'O+', 'O-', 'AB+', 'AB-')
     or coalesce(p_units, 0) not between 1 and 10
     or length(trim(coalesce(p_address, ''))) not between 3 and 250
     or length(trim(coalesce(p_city, ''))) not between 2 and 100
     or coalesce(p_urgency, 'emergency') not in ('emergency', 'urgent', 'scheduled')
     or length(coalesce(p_notes, '')) > 500
     or length(coalesce(p_hospital, '')) > 150 then
    raise exception using errcode = 'P0001', message = 'Please check the blood request details';
  end if;
  perform pg_advisory_xact_lock(hashtext(v_profile_id::text || ':blood-requests'));
  if (select count(*) from public.blood_requests
      where user_id = v_profile_id and status = 'open') >= 3 then
    raise exception using errcode = 'P0001',
      message = 'You already have 3 open requests. Cancel or wait for one to be fulfilled.';
  end if;

  insert into public.blood_requests (
    user_id, patient_name, contact_person, contact_number, blood_group,
    units, hospital, address, city, urgency, notes
  ) values (
    v_profile_id, trim(p_patient_name), trim(p_contact_person), trim(p_contact_number),
    p_blood_group, p_units, nullif(trim(p_hospital), ''), trim(p_address),
    trim(p_city), coalesce(p_urgency, 'emergency'), nullif(trim(p_notes), '')
  ) returning * into v_request;
  insert into public.notifications (user_id, type, title, body)
  values (null, 'emergency', 'Blood Emergency Request',
          'Urgently need ' || p_blood_group || ' donors in ' || trim(p_city));
  return v_request;
end;
$$;

